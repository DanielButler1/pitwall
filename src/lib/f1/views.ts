type NationMembers = { drivers: string[]; constructors: string[]; engines: string[]; tyres: string[]; races: Race[]; circuits: Set<string> };

/** Everything attached to each country: drivers by nationality, constructors/engines/tyres by origin, races by circuit location. */
function nationMembers(db: Db): Map<string, NationMembers> {
	return cached(db, "nations", () => {
		const m = new Map<string, NationMembers>();
		const get = (id: string) => {
			let n = m.get(id);
			if (!n) m.set(id, (n = { drivers: [], constructors: [], engines: [], tyres: [], races: [], circuits: new Set() }));
			return n;
		};
		for (const id of db.resultsByDriver.keys()) {
			const d = db.drivers.get(id);
			if (d) get(d.nationality).drivers.push(id);
		}
		for (const id of db.resultsByConstructor.keys()) {
			const c = db.constructors.get(id);
			if (c) get(c.country).constructors.push(id);
		}
		for (const id of resultsBySupplier(db, "engine").keys()) {
			const e = db.engines.get(id);
			if (e) get(e.country).engines.push(id);
		}
		for (const id of resultsBySupplier(db, "tyre").keys()) {
			const t = db.tyres.get(id);
			if (t) get(t.country).tyres.push(id);
		}
		for (const race of db.races) {
			const c = db.circuits.get(race.circuitId);
			if (!c || !db.resultsByRace.has(race.id)) continue;
			const n = get(c.country);
			n.races.push(race);
			n.circuits.add(c.id);
		}
		return m;
	});
}

