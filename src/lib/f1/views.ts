function racesByGrandPrix(db: Db): Map<string, Race[]> {
	return cached(db, "racesByGp", () => {
		const m = new Map<string, Race[]>();
		for (const r of db.races) {
			const list = m.get(r.grandPrixId);
			if (list) list.push(r);
			else m.set(r.grandPrixId, [r]);
		}
		return m;
	});
}

const topCounts = <T,>(m: Map<string, number>, f: (id: string) => T, limit = 10) =>
	[...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, limit).map(([k, n]) => ({ ref: f(k), n }));
const bump = (m: Map<string, number>, k: string) => m.set(k, (m.get(k) ?? 0) + 1);

export type GrandsPrixView = {
	rows: {
		gp: GrandPrixRef;
		shortName: string;
		nation: NationRef;
		races: number;
		firstYear: number | null;
		lastYear: number | null;
		circuits: number;
		topDriver: { driver: DriverRef; wins: number } | null;
		lastWinner: DriverRef | null;
	}[];
};

export function grandsPrixView(db: Db): GrandsPrixView {
	return {
		rows: [...db.grandsPrix.values()]
			.map((g) => {
				const races = (racesByGrandPrix(db).get(g.id) ?? []).filter((r) => db.resultsByRace.has(r.id));
				const wins = new Map<string, number>();
				let last: string | null = null;
				for (const race of races) {
					const w = winnerOf(db, race.id);
					if (!w) continue;
					bump(wins, w.driverId);
					last = w.driverId;
				}
				const top = topCounts(wins, (k) => driverRef(db, k), 1)[0];
				return {
					gp: grandPrixRef(db, g.id),
					shortName: g.shortName,
					nation: nationRef(db, g.country),
					races: races.length,
					firstYear: races[0]?.year ?? null,
					lastYear: races[races.length - 1]?.year ?? null,
					circuits: new Set(races.map((r) => r.circuitId)).size,
					topDriver: top ? { driver: top.ref, wins: top.n } : null,
					lastWinner: last ? driverRef(db, last) : null,
				};
			})
			.filter((r) => r.races > 0 || (racesByGrandPrix(db).get(r.gp.id)?.length ?? 0) > 0)
			.sort((a, b) => b.races - a.races || (b.lastYear ?? 0) - (a.lastYear ?? 0)),
	};
}

export type GrandPrixView = {
	gp: GrandPrixRef & { shortName: string };
	nation: NationRef;
	totals: { races: number; firstYear: number | null; lastYear: number | null; circuits: number; winners: number };
	/** Every edition, newest first (including scheduled ones). */
	editions: { race: RaceRef; circuit: CircuitRef; completed: boolean; pole: DriverRef | null; winner: DriverRef | null; team: TeamRef | null }[];
	topDrivers: { driver: DriverRef; wins: number }[];
	topTeams: { team: TeamRef; wins: number }[];
	topEngines: { engine: EngineRef; wins: number }[];
	circuits: { circuit: CircuitRef; races: number; firstYear: number; lastYear: number }[];
};

export function grandPrixView(db: Db, id: string): GrandPrixView | null {
	const g = db.grandsPrix.get(id);
	if (!g) return null;
	const all = racesByGrandPrix(db).get(id) ?? [];
	const done = all.filter((r) => db.resultsByRace.has(r.id));
	const dWins = new Map<string, number>();
	const tWins = new Map<string, number>();
	const eWins = new Map<string, number>();
	const editions = all.map((race) => {
		const w = winnerOf(db, race.id);
		const p = poleOf(db, race.id);
		if (w) {
			bump(dWins, w.driverId);
			bump(tWins, w.constructorId);
			bump(eWins, w.engineId);
		}
		return {
			race: raceRef(db, race),
			circuit: circuitRef(db, race.circuitId),
			completed: db.resultsByRace.has(race.id),
			pole: p ? driverRef(db, p.driverId) : null,
			winner: w ? driverRef(db, w.driverId) : null,
			team: w ? teamRef(db, w.constructorId) : null,
		};
	});
	return {
		gp: { ...grandPrixRef(db, id), shortName: g.shortName },
		nation: nationRef(db, g.country),
		totals: {
			races: done.length,
			firstYear: done[0]?.year ?? null,
			lastYear: done[done.length - 1]?.year ?? null,
			circuits: new Set(done.map((r) => r.circuitId)).size,
			winners: dWins.size,
		},
		editions: editions.reverse(),
		topDrivers: topCounts(dWins, (k) => driverRef(db, k)).map(({ ref, n }) => ({ driver: ref, wins: n })),
		topTeams: topCounts(tWins, (k) => teamRef(db, k)).map(({ ref, n }) => ({ team: ref, wins: n })),
		topEngines: topCounts(eWins, (k) => engineRef(db, k)).map(({ ref, n }) => ({ engine: ref, wins: n })),
		circuits: spans(done.length ? done : all, (r) => r.circuitId).map((s) => ({ circuit: circuitRef(db, s.key), races: s.races, firstYear: s.firstYear, lastYear: s.lastYear })),
	};
}

