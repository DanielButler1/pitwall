export type SeasonsView = {
	rows: {
		year: number;
		races: number;
		champion: DriverRef | null;
		championTeam: TeamRef | null;
		championPoints: number | null;
		constructorChampion: TeamRef | null;
		/** Still being run: champion fields hold the current leaders. */
		inProgress: boolean;
		modified: boolean;
		simulated: boolean;
		realChampion: DriverRef | null;
	}[];
};

function championTeam(db: Db, year: number, driverId: string): TeamRef | null {
	const counts = new Map<string, number>();
	for (const race of completedRaces(db, year)) {
		for (const r of db.resultsByRace.get(race.id) ?? []) {
			if (r.driverId === driverId) counts.set(r.constructorId, (counts.get(r.constructorId) ?? 0) + 1);
		}
	}
	const top = [...counts.entries()].sort((a, b) => b[1] - a[1])[0];
	return top ? teamRef(db, top[0]) : null;
}

export function seasonsView(db: Db, base?: Db): SeasonsView {
	const rows: SeasonsView["rows"] = [];
	for (const year of [...db.years].reverse()) {
		const races = completedRaces(db, year);
		const { drivers, constructors } = seasonStandings(db, year);
		const champ = drivers.find((d) => d.champion) ?? (races.length ? drivers[0] : undefined);
		const inProgress = seasonInProgress(db, year);
		const cChamp = constructors.find((c) => c.champion) ?? (inProgress ? constructors[0] : undefined);
		const realStandings = base?.driverStandings.get(year);
		const realChamp = realStandings?.find((d) => d.champion) ?? (inProgress ? realStandings?.[0] : undefined);
		rows.push({
			year,
			races: races.length || (db.racesByYear.get(year)?.length ?? 0),
			champion: champ ? driverRef(db, champ.id) : null,
			championTeam: champ ? championTeam(db, year, champ.id) : null,
			championPoints: champ ? champ.points : null,
			constructorChampion: cChamp ? teamRef(db, cChamp.id) : null,
			inProgress,
			modified: db.modifiedYears?.has(year) ?? false,
			simulated: isSimulated(db, year),
			realChampion: realChamp && champ && realChamp.id !== champ.id ? driverRef(db, realChamp.id) : null,
		});
	}
	return { rows };
}

