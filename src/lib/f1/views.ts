export type MatrixCell = { text: string; points: number; pole: boolean; fastestLap: boolean } | null;

export type SeasonView = {
	year: number;
	prevYear: number | null;
	nextYear: number | null;
	completed: boolean;
	inProgress: boolean;
	modified: boolean;
	simulated: boolean;
	pointsSystem: string;
	races: {
		race: RaceRef;
		circuit: CircuitRef;
		completed: boolean;
		sprint: boolean;
		winner: DriverRef | null;
		winnerTeam: TeamRef | null;
		pole: DriverRef | null;
		fastestLap: DriverRef | null;
	}[];
	driverStandings: {
		position: string;
		driver: DriverRef;
		teams: TeamRef[];
		points: number;
		wins: number;
		champion: boolean;
		cells: MatrixCell[];
		realPosition: string | null;
	}[];
	constructorStandings: {
		position: string;
		team: TeamRef;
		engine: EngineRef | null;
		points: number;
		wins: number;
		champion: boolean;
		realPosition: string | null;
	}[];
	entrants: { team: TeamRef; engine: EngineRef | null; drivers: DriverRef[] }[];
	/** Tyre suppliers used during the season. */
	tyres: TyreRef[];
};

export function seasonView(db: Db, year: number, base?: Db): SeasonView | null {
	const allRaces = db.racesByYear.get(year);
	if (!allRaces) return null;
	const races = completedRaces(db, year);
	const { drivers, constructors } = seasonStandings(db, year);
	const realDrivers = base && db.modifiedYears?.has(year) ? base.driverStandings.get(year) : undefined;
	const realConstructors = base && db.modifiedYears?.has(year) ? base.constructorStandings.get(year) : undefined;

	// per-driver per-race matrix + teams + wins
	const cells = new Map<string, MatrixCell[]>();
	const teams = new Map<string, Set<string>>();
	const wins = new Map<string, number>();
	const teamWins = new Map<string, number>();
	races.forEach((race, i) => {
		for (const r of db.resultsByRace.get(race.id) ?? []) {
			let row = cells.get(r.driverId);
			if (!row) cells.set(r.driverId, (row = new Array(races.length).fill(null)));
			const prev = row[i];
			// shared drives: keep the better result
			if (!prev || (r.position ?? 999) < (Number(prev.text) || 999)) {
				row[i] = { text: r.positionText, points: r2(r.points), pole: r.pole, fastestLap: r.fastestLap };
			}
			if (!teams.has(r.driverId)) teams.set(r.driverId, new Set());
			teams.get(r.driverId)!.add(r.constructorId);
			if (r.position === 1) {
				wins.set(r.driverId, (wins.get(r.driverId) ?? 0) + 1);
				teamWins.set(r.constructorId, (teamWins.get(r.constructorId) ?? 0) + 1);
			}
		}
	});

	const realPos = (rows: StandingRow[] | undefined, id: string, engineId?: string) => {
		if (!rows) return null;
		const r = rows.find((x) => x.id === id && (engineId === undefined || x.engineId === engineId));
		return r?.positionText ?? "–";
	};

	const yearsWithRaces = db.years;
	const idx = yearsWithRaces.indexOf(year);
	const entrantsByTeam = new Map<string, { engine: string; drivers: string[] }>();
	for (const e of db.upcomingEntrants.filter((e) => e.year === year)) {
		const t = entrantsByTeam.get(e.constructorId) ?? { engine: e.engineId, drivers: [] };
		t.drivers.push(e.driverId);
		entrantsByTeam.set(e.constructorId, t);
	}

	return {
		year,
		prevYear: idx > 0 ? yearsWithRaces[idx - 1] : null,
		nextYear: idx < yearsWithRaces.length - 1 ? yearsWithRaces[idx + 1] : null,
		completed: races.length > 0,
		inProgress: seasonInProgress(db, year),
		modified: db.modifiedYears?.has(year) ?? false,
		simulated: isSimulated(db, year),
		pointsSystem: (db.rulesOverride?.get(year)?.system.name) ?? "Official",
		races: allRaces.map((race) => {
			const w = winnerOf(db, race.id);
			const p = poleOf(db, race.id);
			const fl = db.fastestLapByRace.get(race.id);
			return {
				race: raceRef(db, race),
				circuit: circuitRef(db, race.circuitId),
				completed: db.resultsByRace.has(race.id),
				sprint: race.hasSprint,
				winner: w ? driverRef(db, w.driverId) : null,
				winnerTeam: w ? teamRef(db, w.constructorId) : null,
				pole: p ? driverRef(db, p.driverId) : null,
				fastestLap: fl ? driverRef(db, fl.driverId) : null,
			};
		}),
		driverStandings: drivers.map((s) => ({
			position: s.positionText,
			driver: driverRef(db, s.id),
			teams: [...(teams.get(s.id) ?? [])].map((t) => teamRef(db, t)),
			points: r2(s.points),
			wins: wins.get(s.id) ?? 0,
			champion: s.champion,
			cells: cells.get(s.id) ?? new Array(races.length).fill(null),
			realPosition: realPos(realDrivers, s.id),
		})),
		constructorStandings: constructors.map((s) => ({
			position: s.positionText,
			team: teamRef(db, s.id),
			engine: optEngine(db, s.engineId),
			points: r2(s.points),
			wins: teamWins.get(s.id) ?? 0,
			champion: s.champion,
			realPosition: realPos(realConstructors, s.id, s.engineId),
		})),
		entrants: [...entrantsByTeam.entries()].map(([id, t]) => ({
			team: teamRef(db, id),
			engine: optEngine(db, t.engine),
			drivers: t.drivers.map((d) => driverRef(db, d)),
		})),
		tyres: ids(races.flatMap((race) => (db.resultsByRace.get(race.id) ?? []).map((r) => r.tyreId))).map((t) => tyreRef(db, t)),
	};
}

