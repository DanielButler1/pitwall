export type CareerTotals = Pick<Career, "starts" | "wins" | "podiums" | "poles" | "fastestLaps" | "points" | "titles"> & {
	firstYear: number;
	lastYear: number;
};
const totals = (c: Career): CareerTotals => ({
	starts: c.starts,
	wins: c.wins,
	podiums: c.podiums,
	poles: c.poles,
	fastestLaps: c.fastestLaps,
	points: c.points,
	titles: c.titles,
	firstYear: c.firstYear,
	lastYear: c.lastYear,
});

export type DriversView = { rows: (CareerTotals & { driver: DriverRef })[] };

export function driversView(db: Db): DriversView {
	const careers = driverCareers(db);
	return {
		rows: [...careers.values()]
			.map((c) => ({ driver: driverRef(db, c.id), ...totals(c) }))
			.sort((a, b) => b.lastYear - a.lastYear || b.wins - a.wins || a.driver.name.localeCompare(b.driver.name)),
	};
}

