export type RaceView = {
	race: RaceRef;
	raceId: number;
	officialName: string;
	grandPrix: GrandPrixRef;
	/** Country hosting the Grand Prix. */
	nation: NationRef | null;
	circuit: CircuitRef;
	/** Tyre suppliers used in the race. */
	tyres: TyreRef[];
	laps: number;
	distance: number;
	completed: boolean;
	modified: boolean;
	prev: RaceRef | null;
	next: RaceRef | null;
	results: ResultRow[];
	sprint: ResultRow[];
	qualifying: { position: string; driver: DriverRef; team: TeamRef; time: string | null; q1: string | null; q2: string | null; q3: string | null }[];
	fastestLap: { driver: DriverRef; lap: number | null; time: string | null } | null;
	standingsAfter: { drivers: { position: string; driver: DriverRef; points: number }[]; constructors: { position: string; team: TeamRef; points: number }[] };
	/** Who led which laps (Jolpica, since 1996); null without lap data or when a universe changed the race. */
	lapsLed: { driver: DriverRef; laps: number; spans: [number, number][] }[] | null;
	/** Lap-by-lap data available for this race (lap chart, and pit stops from 2011): loaded separately per race. */
	lapData: { chart: boolean; pitStops: boolean; sprintChart: boolean; dumpDate: string | null } | null;
};

function resultRows(db: Db, results: Result[], real?: Result[]): ResultRow[] {
	return results.map((r) => ({
		position: r.positionText,
		number: r.number,
		driver: driverRef(db, r.driverId),
		team: teamRef(db, r.constructorId),
		engine: optEngine(db, r.engineId),
		tyre: optTyre(db, r.tyreId),
		laps: r.laps,
		timeOrStatus: r.position === 1 ? r.time : (r.gap ?? r.time ?? r.reasonRetired),
		grid: r.grid,
		points: r2(r.points),
		fastestLap: r.fastestLap,
		realPosition: real ? (real.find((x) => x.driverId === r.driverId)?.positionText ?? "–") : null,
	}));
}

export function findRace(db: Db, year: number, round: number) {
	return db.racesByYear.get(year)?.find((r) => r.round === round);
}

export function raceView(db: Db, year: number, round: number, base?: Db): RaceView | null {
	const race = findRace(db, year, round);
	if (!race) return null;
	const seasonRaces = db.racesByYear.get(year)!;
	const i = seasonRaces.indexOf(race);
	const flatIndex = db.races.indexOf(race);
	const prev = db.races[flatIndex - 1];
	const next = db.races[flatIndex + 1];
	const results = db.resultsByRace.get(race.id) ?? [];
	const realResults = base?.resultsByRace.get(race.id);
	const changed = Boolean(realResults && realResults.map((r) => r.driverId + r.positionText).join() !== results.map((r) => r.driverId + r.positionText).join());
	const completed = results.length > 0;
	const after = completed ? standingsAfter(db, race) : { drivers: [], constructors: [] };
	const gp = db.grandsPrix.get(race.grandPrixId);
	const fl = db.fastestLapByRace.get(race.id);
	void i;
	return {
		race: raceRef(db, race),
		raceId: race.id,
		officialName: race.officialName,
		grandPrix: gp ? grandPrixRef(db, gp.id) : { id: race.grandPrixId, name: race.officialName, country: null },
		nation: gp ? nationRef(db, gp.country) : null,
		circuit: circuitRef(db, race.circuitId),
		tyres: ids(results.map((r) => r.tyreId)).map((t) => tyreRef(db, t)),
		laps: race.laps,
		distance: race.distance,
		completed,
		modified: changed,
		prev: prev ? raceRef(db, prev) : null,
		next: next ? raceRef(db, next) : null,
		results: resultRows(db, results, changed ? realResults : undefined),
		sprint: resultRows(db, db.sprintByRace.get(race.id) ?? []),
		qualifying: (db.qualifyingByRace.get(race.id) ?? []).map((q) => ({
			position: q.positionText,
			driver: driverRef(db, q.driverId),
			team: teamRef(db, q.constructorId),
			time: q.time,
			q1: q.q1,
			q2: q.q2,
			q3: q.q3,
		})),
		fastestLap: fl ? { driver: driverRef(db, fl.driverId), lap: fl.lap, time: fl.time } : null,
		lapsLed: lapsLedSummary(db, race.id),
		lapData: lapDataFlags(db, race),
		standingsAfter: {
			drivers: after.drivers.slice(0, 10).map((s) => ({ position: s.positionText, driver: driverRef(db, s.id), points: r2(s.points) })),
			constructors: after.constructors.slice(0, 10).map((s) => ({ position: s.positionText, team: teamRef(db, s.id), points: r2(s.points) })),
		},
	};
}

function lapsLedSummary(db: Db, raceId: number): RaceView["lapsLed"] {
	const spans = lapLeaders(db, raceId);
	if (!spans) return null;
	const by = new Map<string, [number, number][]>();
	for (const [d, a, b] of spans) by.set(d, [...(by.get(d) ?? []), [a, b]]);
	return [...by]
		.map(([d, list]) => ({ driver: driverRef(db, d), laps: list.reduce((n, [a, b]) => n + b - a + 1, 0), spans: list }))
		.sort((a, b) => b.laps - a.laps || a.spans[0][0] - b.spans[0][0]);
}

function lapDataFlags(db: Db, race: Race): RaceView["lapData"] {
	if (!hasLapData(db, race.id)) return null;
	const meta = db.meta.jolpica;
	return {
		chart: true,
		pitStops: meta?.pitStopsFrom != null && race.year >= meta.pitStopsFrom,
		sprintChart: sprintLapLeaders(db, race.id) != null,
		dumpDate: meta?.dumpDate ?? null,
	};
}

