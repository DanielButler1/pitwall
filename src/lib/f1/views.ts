// View-model builders: one per page. They return plain serialisable objects so
// server pages can pass them to components, and the universe renderer can call
// the very same builders in the browser on a modified Db.
//
// `base` (optional) is the real-history Db; when given, views include
// "in reality" comparisons for anything the universe changed.

