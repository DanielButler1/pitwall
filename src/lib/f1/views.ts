export type SupplierKind = "engine" | "tyre";
const supplierKey = { engine: "engineId", tyre: "tyreId" } as const;
/** Engines and tyres share one shape. */
export type SupplierRef = EngineRef;

const supplierRef = (db: Db, kind: SupplierKind, id: string): SupplierRef => (kind === "engine" ? engineRef(db, id) : tyreRef(db, id));
const supplierMap = (db: Db, kind: SupplierKind) => (kind === "engine" ? db.engines : db.tyres);

/** Results per engine / tyre supplier, chronological. */
function resultsBySupplier(db: Db, kind: SupplierKind): Map<string, Result[]> {
	return cached(db, `by:${kind}`, () => {
		const key = supplierKey[kind];
		const m = new Map<string, Result[]>();
		for (const race of db.races) {
			for (const r of db.resultsByRace.get(race.id) ?? []) {
				const k = r[key];
				if (!k) continue;
				const list = m.get(k);
				if (list) list.push(r);
				else m.set(k, [r]);
			}
		}
		return m;
	});
}

export type SupplierTotals = {
	races: number;
	wins: number;
	podiums: number;
	poles: number;
	fastestLaps: number;
	driversTitles: number;
	constructorsTitles: number;
	teams: number;
	drivers: number;
	seasons: number;
	firstYear: number | null;
	lastYear: number | null;
};

function supplierTotals(db: Db, kind: SupplierKind, id: string): SupplierTotals {
	return cached(db, `totals:${kind}:${id}`, () => {
		const rs = resultsBySupplier(db, kind).get(id) ?? [];
		const races = new Set<number>();
		const wins = new Set<number>();
		const poles = new Set<number>();
		const fls = new Set<number>();
		const years = new Set<number>();
		const teams = new Set<string>();
		const drivers = new Set<string>();
		let podiums = 0;
		for (const r of rs) {
			races.add(r.raceId);
			years.add(yearOf(db, r));
			teams.add(r.constructorId);
			drivers.add(r.driverId);
			if (r.position === 1) wins.add(r.raceId);
			if (r.position != null && r.position <= 3) podiums++;
			if (r.pole) poles.add(r.raceId);
			if (r.fastestLap) fls.add(r.raceId);
		}
		const key = supplierKey[kind];
		const credits = titleCredits(db).filter((c) => c[key] === id);
		const y = [...years].sort((a, b) => a - b);
		return {
			races: races.size,
			wins: wins.size,
			podiums,
			poles: poles.size,
			fastestLaps: fls.size,
			driversTitles: credits.filter((c) => c.kind === "drivers").length,
			constructorsTitles: credits.filter((c) => c.kind === "constructors").length,
			teams: teams.size,
			drivers: drivers.size,
			seasons: y.length,
			firstYear: y[0] ?? null,
			lastYear: y[y.length - 1] ?? null,
		};
	});
}

