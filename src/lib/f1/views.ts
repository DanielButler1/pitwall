export function constructorView(db: Db, id: string, base?: Db): ConstructorView | null {
	const c = db.constructors.get(id);
	if (!c) return null;
	const career = constructorCareers(db).get(id);
	const realCareer = base ? constructorCareers(base).get(id) : undefined;
	const results = db.resultsByConstructor.get(id) ?? [];
	const byYear = new Map<number, Result[]>();
	const perDriver = new Map<string, { starts: number; wins: number; points: number }>();
	for (const r of results) {
		const y = db.raceById.get(r.raceId)!.year;
		if (!byYear.has(y)) byYear.set(y, []);
		byYear.get(y)!.push(r);
		const p = perDriver.get(r.driverId) ?? { starts: 0, wins: 0, points: 0 };
		if (isStart(r)) p.starts++;
		if (r.position === 1) p.wins++;
		p.points += r.points;
		perDriver.set(r.driverId, p);
	}
	const t = career ? totals(career) : null;
	const rt = realCareer ? totals(realCareer) : null;
	return {
		team: { ...teamRef(db, id), fullName: c.fullName, countryName: db.countries.get(c.country)?.name ?? null },
		nation: nationRef(db, c.country),
		totals: {
			...(t ?? { starts: 0, wins: 0, podiums: 0, poles: 0, fastestLaps: 0, points: 0, titles: 0, firstYear: 0, lastYear: 0 }),
			entries: career?.entries ?? 0,
			oneTwos: career?.oneTwos ?? 0,
		},
		realTotals: t && rt && JSON.stringify(t) !== JSON.stringify(rt) ? rt : null,
		seasons: [...byYear.entries()].map(([year, rs]) => {
			const standings = (db.constructorStandings.get(year) ?? []).filter((s) => s.id === id);
			const bestStanding = standings.sort((a, b) => (a.position ?? 999) - (b.position ?? 999))[0];
			return {
				year,
				position: bestStanding?.positionText ?? null,
				points: r2(standings.reduce((a, s) => a + s.points, 0)),
				wins: rs.filter((r) => r.position === 1).length,
				drivers: [...new Set(rs.map((r) => r.driverId))].map((d) => driverRef(db, d)),
				engines: ids(rs.map((r) => r.engineId)).map((e) => engineRef(db, e)),
				tyres: ids(rs.map((r) => r.tyreId)).map((t) => tyreRef(db, t)),
				champion: standings.some((s) => s.champion),
			};
		}),
		topDrivers: [...perDriver.entries()]
			.sort((a, b) => b[1].starts - a[1].starts)
			.slice(0, 15)
			.map(([d, p]) => ({ driver: driverRef(db, d), ...p, points: r2(p.points) })),
		wins: results
			.filter((r) => r.position === 1)
			.map((r) => ({ race: raceRef(db, db.raceById.get(r.raceId)!), driver: driverRef(db, r.driverId) }))
			.reverse(),
	};
}

