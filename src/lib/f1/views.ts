/** Compact global search index: [kind, id, label, alpha2 flag or "", extra keywords]. */
export type SearchKind = "driver" | "constructor" | "circuit" | "grandPrix" | "engine" | "tyre" | "nation" | "season";
export type SearchEntry = [SearchKind, string, string, string, string];

export function searchIndex(db: Db): SearchEntry[] {
	const dc = driverCareers(db);
	const out: SearchEntry[] = [];
	const flag = (countryId: string) => db.countries.get(countryId)?.alpha2.toLowerCase() ?? "";
	const years = (a?: number | null, b?: number | null) => (a ? (a === b ? String(a) : `${a}-${b}`) : "");
	for (const [id, c] of [...dc.entries()].sort((a, b) => b[1].wins - a[1].wins || b[1].starts - a[1].starts)) {
		const d = db.drivers.get(id);
		if (d) out.push(["driver", id, d.name, flag(d.nationality), years(c.firstYear, c.lastYear)]);
	}
	for (const [id, c] of [...constructorCareers(db).entries()].sort((a, b) => b[1].wins - a[1].wins || b[1].entries - a[1].entries)) {
		const t = db.constructors.get(id);
		if (t) out.push(["constructor", id, t.name, flag(t.country), [t.fullName ?? "", years(c.firstYear, c.lastYear)].join(" ").trim()]);
	}
	for (const g of grandsPrixView(db).rows) out.push(["grandPrix", g.gp.id, g.gp.name, g.gp.country?.toLowerCase() ?? "", g.shortName]);
	for (const c of circuitsView(db).rows) out.push(["circuit", c.id, c.name, c.country?.toLowerCase() ?? "", [c.place, c.countryName ?? ""].join(" ")]);
	for (const e of enginesView(db).rows) out.push(["engine", e.supplier.id, e.supplier.name, e.supplier.country?.toLowerCase() ?? "", years(e.firstYear, e.lastYear)]);
	for (const e of tyresView(db).rows) out.push(["tyre", e.supplier.id, e.supplier.name, e.supplier.country?.toLowerCase() ?? "", years(e.firstYear, e.lastYear)]);
	for (const n of nationsView(db).rows) out.push(["nation", n.nation.id, n.nation.name, n.nation.country?.toLowerCase() ?? "", db.countries.get(n.nation.id)?.demonym ?? ""]);
	for (const y of [...db.years].reverse()) out.push(["season", String(y), `${y} season`, "", ""]);
	return out;
}


