export type DriverRef = { id: string; name: string; country: string | null; countryName: string | null };
export type TeamRef = { id: string; name: string; country: string | null };
export type RaceRef = { year: number; round: number; name: string; date: string; country: string | null };
export type CircuitRef = { id: string; name: string; place: string; country: string | null };
/** `country` fields on refs are ISO alpha-2 codes for flags; `id` on NationRef is the F1DB country id used in URLs. */
export type EngineRef = { id: string; name: string; country: string | null };
export type TyreRef = { id: string; name: string; country: string | null };
export type NationRef = { id: string; name: string; country: string | null };
export type GrandPrixRef = { id: string; name: string; country: string | null };

const r2 = (n: number) => Math.round(n * 100) / 100;

export function driverRef(db: Db, id: string): DriverRef {
	const d = db.drivers.get(id);
	const c = d ? db.countries.get(d.nationality) : undefined;
	return { id, name: d?.name ?? id, country: c?.alpha2 ?? null, countryName: c?.name ?? null };
}
export function teamRef(db: Db, id: string): TeamRef {
	const t = db.constructors.get(id);
	return { id, name: t?.name ?? id, country: (t && db.countries.get(t.country)?.alpha2) ?? null };
}
export function raceRef(db: Db, race: Race): RaceRef {
	const gp = db.grandsPrix.get(race.grandPrixId);
	return {
		year: race.year,
		round: race.round,
		name: gp?.name ?? race.officialName,
		date: race.date,
		country: (gp && db.countries.get(gp.country)?.alpha2) ?? null,
	};
}
export function circuitRef(db: Db, id: string): CircuitRef {
	const c = db.circuits.get(id);
	return { id, name: c?.name ?? id, place: c?.place ?? "", country: (c && db.countries.get(c.country)?.alpha2) ?? null };
}
export function engineRef(db: Db, id: string): EngineRef {
	const e = db.engines.get(id);
	return { id, name: e?.name ?? id, country: (e && db.countries.get(e.country)?.alpha2) ?? null };
}
export function tyreRef(db: Db, id: string): TyreRef {
	const t = db.tyres.get(id);
	return { id, name: t?.name ?? id, country: (t && db.countries.get(t.country)?.alpha2) ?? null };
}
export function nationRef(db: Db, countryId: string): NationRef {
	const c = db.countries.get(countryId);
	return { id: countryId, name: c?.name ?? countryId, country: c?.alpha2 ?? null };
}
/** Seasons the universe generated by simulation (as opposed to edited or re-scored). */
const isSimulated = (db: Db, year: number) => Boolean((db as Db & { sim?: { years: number[] } }).sim?.years.includes(year));

export function grandPrixRef(db: Db, id: string): GrandPrixRef {
	const g = db.grandsPrix.get(id);
	return { id, name: g?.fullName ?? id, country: (g && db.countries.get(g.country)?.alpha2) ?? null };
}
const optEngine = (db: Db, id: string | null | undefined) => (id ? engineRef(db, id) : null);
const optTyre = (db: Db, id: string | null | undefined) => (id ? tyreRef(db, id) : null);
const uniq = <T,>(xs: T[]) => [...new Set(xs)];
const ids = (xs: (string | null | undefined)[]) => uniq(xs.filter((x): x is string => !!x));

const memo = new WeakMap<Db, Map<string, unknown>>();
function cached<T>(db: Db, key: string, compute: () => T): T {
	let m = memo.get(db);
	if (!m) memo.set(db, (m = new Map()));
	if (!m.has(key)) m.set(key, compute());
	return m.get(key) as T;
}
const yearOf = (db: Db, r: Result) => db.raceById.get(r.raceId)!.year;
/** Most frequent value (first seen wins ties). */
function mode<T>(xs: T[]): T | undefined {
	const counts = new Map<T, number>();
	let best: T | undefined;
	let bestN = 0;
	for (const x of xs) {
		const n = (counts.get(x) ?? 0) + 1;
		counts.set(x, n);
		if (n > bestN) [best, bestN] = [x, n];
	}
	return best;
}
/** Group races by a key: count and first/last year, most races first. */
function spans(races: Race[], key: (r: Race) => string) {
	const m = new Map<string, { key: string; races: number; firstYear: number; lastYear: number }>();
	for (const r of races) {
		const k = key(r);
		const s = m.get(k);
		if (s) {
			s.races++;
			s.firstYear = Math.min(s.firstYear, r.year);
			s.lastYear = Math.max(s.lastYear, r.year);
		} else m.set(k, { key: k, races: 1, firstYear: r.year, lastYear: r.year });
	}
	return [...m.values()].sort((a, b) => b.races - a.races || b.lastYear - a.lastYear);
}

