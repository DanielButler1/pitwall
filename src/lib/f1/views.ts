export type CircuitView = {
	circuit: CircuitRef & { fullName: string; countryName: string | null; type: string; direction: string; length: number; turns: number; lat: number; lng: number };
	nation: NationRef;
	races: { race: RaceRef; grandPrix: GrandPrixRef; winner: DriverRef | null; team: TeamRef | null; pole: DriverRef | null }[];
	topDrivers: { driver: DriverRef; wins: number }[];
	topTeams: { team: TeamRef; wins: number }[];
	/** Grands Prix held at this circuit. */
	grandsPrix: { gp: GrandPrixRef; races: number; firstYear: number; lastYear: number }[];
};

export function circuitView(db: Db, id: string): CircuitView | null {
	const c = db.circuits.get(id);
	if (!c) return null;
	const races = (db.racesByCircuit.get(id) ?? []).filter((r) => db.resultsByRace.has(r.id));
	const dWins = new Map<string, number>();
	const tWins = new Map<string, number>();
	const rows = races.map((race) => {
		const w = winnerOf(db, race.id);
		const p = poleOf(db, race.id);
		if (w) {
			dWins.set(w.driverId, (dWins.get(w.driverId) ?? 0) + 1);
			tWins.set(w.constructorId, (tWins.get(w.constructorId) ?? 0) + 1);
		}
		return {
			race: raceRef(db, race),
			grandPrix: grandPrixRef(db, race.grandPrixId),
			winner: w ? driverRef(db, w.driverId) : null,
			team: w ? teamRef(db, w.constructorId) : null,
			pole: p ? driverRef(db, p.driverId) : null,
		};
	});
	const top = <T,>(m: Map<string, number>, f: (id: string) => T) =>
		[...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, 10).map(([k, wins]) => ({ ref: f(k), wins }));
	return {
		circuit: {
			...circuitRef(db, id),
			fullName: c.fullName,
			countryName: db.countries.get(c.country)?.name ?? null,
			type: c.type,
			direction: c.direction,
			length: c.length,
			turns: c.turns,
			lat: c.lat,
			lng: c.lng,
		},
		nation: nationRef(db, c.country),
		races: rows.reverse(),
		topDrivers: top(dWins, (k) => driverRef(db, k)).map(({ ref, wins }) => ({ driver: ref, wins })),
		topTeams: top(tWins, (k) => teamRef(db, k)).map(({ ref, wins }) => ({ team: ref, wins })),
		grandsPrix: spans(races, (r) => r.grandPrixId).map((g) => ({ gp: grandPrixRef(db, g.key), races: g.races, firstYear: g.firstYear, lastYear: g.lastYear })),
	};
}

/* ------------------------------------------------- championship credits --- */

/** A completed title with the car that won it: the champion's main team, engine and tyres that season. */
type TitleCredit = { year: number; kind: "drivers" | "constructors"; id: string; teamId: string; engineId: string | null; tyreId: string | null };

function titleCredits(db: Db): TitleCredit[] {
	return cached(db, "titleCredits", () => {
		const out: TitleCredit[] = [];
		for (const year of db.years) {
			const results = completedRaces(db, year).flatMap((r) => db.resultsByRace.get(r.id) ?? []);
			for (const s of db.driverStandings.get(year) ?? []) {
				if (!s.champion) continue;
				const own = results.filter((r) => r.driverId === s.id);
				const teamId = mode(own.map((r) => r.constructorId)) ?? "";
				const car = own.filter((r) => r.constructorId === teamId);
				out.push({ year, kind: "drivers", id: s.id, teamId, engineId: mode(car.map((r) => r.engineId)) ?? null, tyreId: mode(ids(car.map((r) => r.tyreId))) ?? null });
			}
			for (const s of db.constructorStandings.get(year) ?? []) {
				if (!s.champion) continue;
				const car = results.filter((r) => r.constructorId === s.id && (!s.engineId || r.engineId === s.engineId));
				out.push({ year, kind: "constructors", id: s.id, teamId: s.id, engineId: s.engineId ?? mode(car.map((r) => r.engineId)) ?? null, tyreId: mode(ids(car.map((r) => r.tyreId))) ?? null });
			}
		}
		return out;
	});
}

